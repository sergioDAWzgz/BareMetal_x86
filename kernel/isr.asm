BITS 64

; ---------------------------------------------------------------------------
; BareMetal_x86 - interrupt stubs
;
; Every vector pushes a dummy error code when the CPU does not, then the vector
; number, then falls into isr_common which saves the general purpose registers,
; calls the C dispatcher and restores everything before iretq.
; ---------------------------------------------------------------------------

%macro ISR_NOERR 1
global isr%1
isr%1:
    push qword 0
    push qword %1
    jmp isr_common
%endmacro

%macro ISR_ERR 1
global isr%1
isr%1:
    push qword %1
    jmp isr_common
%endmacro

section .text

global divide_error_probe
global divide_error_probe_resume
divide_error_probe:
    xor eax, eax
    xor edx, edx
    div eax                        ; raises #DE, faulting RIP is the next label
divide_error_probe_resume:
    ret

